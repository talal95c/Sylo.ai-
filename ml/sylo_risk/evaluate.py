def evaluate(seed: str = "B") -> dict[str, Any]:
    if seed not in {"B", "C"}:
        raise ValueError("seed must be B or C")
    started = time.perf_counter()
    seed_a = _load_frame("A")
    frame_b = _load_frame("B")
    frame_c = _load_frame("C")
    main_frame, ood_frame = (frame_b, frame_c) if seed == "B" else (frame_c, frame_b)

    result_by_seed: dict[str, dict[str, np.ndarray]] = {}
    for frame, name in ((frame_b, "B"), (frame_c, "C")):
        print(f"Scoring seed {name}", flush=True)
        result_by_seed[name] = _score_engine(frame)

    main_result = result_by_seed[seed]
    main_metrics = _evaluate_predictions(
        main_frame,
        main_result["scores"],
        main_result["tiers"],
        oob_resolvable=main_result["oobResolvable"],
        p95_latency_ms=float(main_result["p95LatencyMs"][0]),
        model_scores=main_result["modelScores"],
    )
    interval_values = main_metrics["confidenceIntervals95"]
    by_typology = _typology_breakdown(main_frame, main_result["tiers"], interval_values)
    ood_result = result_by_seed["C" if seed == "B" else "B"]
    ood_metrics = _evaluate_predictions(
        ood_frame,
        ood_result["scores"],
        ood_result["tiers"],
        oob_resolvable=ood_result["oobResolvable"],
        p95_latency_ms=float(ood_result["p95LatencyMs"][0]),
        model_scores=ood_result["modelScores"],
    )
    ood_metrics["seed"] = "C" if seed == "B" else "B"
    ood_metrics["byTypology"] = _typology_breakdown(ood_frame, ood_result["tiers"], ood_metrics["confidenceIntervals95"])

    rules_tiers_b = result_by_seed["B"]["ruleTiers"]
    degraded = []
    for name, degraded_frame in (("B", frame_b), ("C", frame_c)):
        rules_only = _score_engine(
            degraded_frame, strict_rules=True, rules_only=True
        )
        rules_only_metrics = _evaluate_predictions(
            degraded_frame,
            rules_only["scores"],
            rules_only["tiers"],
            include_ci=False,
        )
        history_missing = _score_engine(
            degraded_frame, no_history=True, strict_rules=True
        )
        history_metrics = _evaluate_predictions(
            degraded_frame,
            history_missing["scores"],
            history_missing["tiers"],
            include_ci=False,
        )
        fallback_lr = _score_engine(
            degraded_frame, strict_rules=True, fallback_lr=True
        )
        fallback_lr_metrics = _evaluate_predictions(
            degraded_frame,
            fallback_lr["scores"],
            fallback_lr["tiers"],
            include_ci=False,
        )
        normal_tiers = result_by_seed[name]["tiers"]
        normal_action_tiers = _action_tiers(
            normal_tiers, result_by_seed[name]["oobResolvable"]
        )
        for mode, degraded_result, degraded_metrics in (
            ("history_missing", history_missing, history_metrics),
            ("model_missing_fallback_lr", fallback_lr, fallback_lr_metrics),
            ("model_missing_rules_only", rules_only, rules_only_metrics),
        ):
            permissive_pct = float(
                np.mean(degraded_result["tiers"] < normal_tiers)
            )
            degraded_action_tiers = _action_tiers(
                degraded_result["tiers"], degraded_result["oobResolvable"]
            )
            permissive_action_pct = float(
                np.mean(degraded_action_tiers < normal_action_tiers)
            )
            risk_tier_transitions = {
                "highToMedium": int(
                    np.count_nonzero(
                        (normal_tiers == int(Tier.HIGH))
                        & (degraded_result["tiers"] == int(Tier.MEDIUM))
                    )
                ),
                "highToLow": int(
                    np.count_nonzero(
                        (normal_tiers == int(Tier.HIGH))
                        & (degraded_result["tiers"] == int(Tier.LOW))
                    )
                ),
                "mediumToLow": int(
                    np.count_nonzero(
                        (normal_tiers == int(Tier.MEDIUM))
                        & (degraded_result["tiers"] == int(Tier.LOW))
                    )
                ),
            }
            degraded.append(
                {
                    "seed": name,
                    "mode": mode,
                    "recallAll": degraded_metrics["recallAll"],
                    "fprMediumPlus": degraded_metrics["fprMediumPlus"],
                    "neverLooser": permissive_pct == 0.0,
                    "permissivePct": permissive_pct,
                    "permissiveActionPct": permissive_action_pct,
                    "riskTierTransitions": risk_tier_transitions,
                    "metrics": degraded_metrics,
                }
            )

    artifact = json.loads((ROOT / "models" / "model.json").read_text(encoding="utf-8"))
    baselines = _baseline_models(seed_a, frame_b, rules_tiers_b)
    ablations = _ablations(seed_a, frame_b, rules_tiers_b)
    model_only_metrics = {
        "B": _model_only_metrics(frame_b, result_by_seed["B"]["modelScores"]),
        "C": _model_only_metrics(frame_c, result_by_seed["C"]["modelScores"]),
    }
    data = {
        "dataset": {
            "seedTrain": "A",
            "seedEval": seed,
            "payments": int(len(main_frame)),
            "days": int(main_frame["day"].nunique()),
            "synthetic": True,
        },
        "metrics": main_metrics,
        "byTypology": by_typology,
        "outOfDistribution": ood_metrics,
        "baselines": baselines,
        "ablations": ablations,
        "modelOnlyMetrics": model_only_metrics,
        "degraded": degraded,
        "legitimateHoldBreakdown": _legitimate_hold_breakdown(
            frame_b,
            result_by_seed["B"]["tiers"],
            result_by_seed["B"]["ruleIds"],
        ),
        "integrity": _integrity_replay(),
        "modelVersion": str(artifact["version"]),
        "generatedAt": datetime.now(timezone.utc).isoformat(),
        "sample": False,
        "limits": LIMITS,
        "runtimeSeconds": time.perf_counter() - started,
        "evaluationRows": {"B": int(len(frame_b)), "C": int(len(frame_c))},
        "frozenThresholds": artifact["thresholds"],
    }
    REPORT_DIR.mkdir(parents=True, exist_ok=True)
    (REPORT_DIR / "metrics.json").write_text(json.dumps(data, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    _append_benchmark(data)
    return data


def main() -> None:
    parser = argparse.ArgumentParser(description="Evaluate the frozen model through the engine risk chain")
    parser.add_argument("--seed", choices=("B", "C"), default="B")
    args = parser.parse_args()
    report = evaluate(args.seed)
    print(json.dumps({"dataset": report["dataset"], "metrics": report["metrics"], "outOfDistribution": report["outOfDistribution"], "runtimeSeconds": report["runtimeSeconds"]}, indent=2))


if __name__ == "__main__":
    main()
