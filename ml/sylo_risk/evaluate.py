def _score_engine(
    frame: pd.DataFrame,
    *,
    no_history: bool = False,
    strict_rules: bool = False,
    rules_only: bool = False,
    fallback_lr: bool = False,
) -> dict[str, np.ndarray]:
    rules = _RecordingRules(strict=strict_rules)
    model = None if rules_only else FallbackRisk() if fallback_lr else ModelRisk()
    if no_history and model is not None:
        model._history = HistoryIndex({})
    recorder = None if model is None else _RecordingModel(model)
    combined = rules if recorder is None else CombinedRisk(rules, recorder)
    scores = np.zeros(len(frame), dtype=np.int16)
    model_scores = np.zeros(len(frame), dtype=np.int16)
    tiers = np.zeros(len(frame), dtype=np.int8)
    rule_tiers = np.zeros(len(frame), dtype=np.int8)
    rule_ids = np.empty(len(frame), dtype=object)
    oob = np.zeros(len(frame), dtype=bool)

    columns = list(ROW_FIELDS)
    for index, values in enumerate(frame.loc[:, columns].itertuples(index=False, name=None)):
        row = dict(zip(columns, values))
        order, ctx = row_to_order_ctx(row)
        if no_history:
            ctx = ctx.model_copy(update={"history": None})
        result = combined.score(order, ctx)
        scores[index] = result.score
        model_scores[index] = result.score if recorder is None else recorder.last_result.score
        tiers[index] = int(result.tier)
        rule_tiers[index] = int(rules.last_result.tier)
        rule_ids[index] = tuple(rules.last_result.rules_fired)
        oob[index] = result.oob_resolvable
        if index and index % 50_000 == 0:
            print(f"Scored {index:,}/{len(frame):,} rows", flush=True)

    latency_indices = np.random.default_rng(0).choice(
        len(frame), size=min(2_000, len(frame)), replace=False
    )
    for index in latency_indices[: min(50, len(latency_indices))]:
        row = dict(zip(columns, frame.iloc[index][columns].tolist()))
        order, ctx = row_to_order_ctx(row)
        if no_history:
            ctx = ctx.model_copy(update={"history": None})
        combined.score(order, ctx)
    latency_ms: list[float] = []
    for index in latency_indices:
        row = dict(zip(columns, frame.iloc[index][columns].tolist()))
        order, ctx = row_to_order_ctx(row)
        if no_history:
            ctx = ctx.model_copy(update={"history": None})
        started = time.perf_counter()
        combined.score(order, ctx)
        latency_ms.append((time.perf_counter() - started) * 1_000)

    return {
        "scores": scores,
        "modelScores": model_scores,
        "tiers": tiers,
        "ruleTiers": rule_tiers,
        "ruleIds": rule_ids,
        "oobResolvable": oob,
        "p95LatencyMs": np.asarray([np.percentile(latency_ms, 95)]),
    }


def _final_tiers(
    probabilities: np.ndarray,
    rule_tiers: np.ndarray,
    t_med: float,
    t_high: float,
) -> tuple[np.ndarray, np.ndarray]:
    scores = np.fromiter(
        (probability_to_score(float(value), t_med, t_high) for value in probabilities),
        dtype=np.int16,
        count=len(probabilities),
    )
    bands = np.where(scores >= 90, Tier.CRITICAL, np.where(scores >= 70, Tier.HIGH, np.where(scores >= 40, Tier.MEDIUM, Tier.LOW)))
    return scores, np.maximum(rule_tiers, bands).astype(np.int8)


def _action_tiers(tiers: np.ndarray, oob_resolvable: np.ndarray) -> np.ndarray:
    return np.where(
        (tiers == int(Tier.HIGH)) & oob_resolvable,
        int(Tier.MEDIUM),
        tiers,
    ).astype(np.int8)


def _model_only_metrics(frame: pd.DataFrame, scores: np.ndarray) -> dict[str, float]:
    tiers = np.fromiter(
        (int(band(int(score))) for score in scores),
        dtype=np.int8,
        count=len(scores),
    )
    labels = frame["label"].to_numpy(dtype=bool)
    typology = frame["typology"].astype(str).to_numpy()
    evasive = frame["evasive"].to_numpy(dtype=bool)
    flagged = tiers >= int(Tier.MEDIUM)
    high = tiers >= int(Tier.HIGH)
    legitimate = ~labels
    return {
        "recallT1": float(flagged[typology == "T1"].mean()),
        "recallT1Evasive": float(flagged[(typology == "T1") & evasive].mean()),
        "recallAll": float(flagged[labels].mean()),
        "precisionHigh": float(labels[high].mean()) if high.any() else 0.0,
        "fprMediumPlus": float(flagged[legitimate].mean()),
    }


def _metric_conditions(
    frame: pd.DataFrame,
    tiers: np.ndarray,
    oob_resolvable: np.ndarray | None = None,
) -> dict[str, tuple[np.ndarray, np.ndarray]]:
    labels = frame["label"].to_numpy(dtype=bool)
    typology = frame["typology"].astype(str).to_numpy()
    evasive = frame["evasive"].to_numpy(dtype=bool)
    hard_negative = frame["hard_negative"].to_numpy(dtype=bool) & ~labels
    flagged = tiers >= int(Tier.MEDIUM)
    high = tiers >= int(Tier.HIGH)
    legit = ~labels
    conditions = {
        "recallT1": (flagged & (typology == "T1"), typology == "T1"),
        "recallT1Evasive": (flagged & (typology == "T1") & evasive, (typology == "T1") & evasive),
        "recallAll": (flagged & labels, labels),
        "precisionHigh": (high & labels, high),
        "fprMediumPlus": (flagged & legit, legit),
        "fprHardNegatives": (flagged & hard_negative, hard_negative),
        "recallT2": (flagged & (typology == "T2"), typology == "T2"),
        "recallT3": (flagged & (typology == "T3"), typology == "T3"),
        "recallT4": (flagged & (typology == "T4"), typology == "T4"),
    }
    if oob_resolvable is not None:
        action_tiers = _action_tiers(tiers, oob_resolvable)
        action_high = action_tiers >= int(Tier.HIGH)
        action_medium = action_tiers == int(Tier.MEDIUM)
        action_friction = action_tiers >= int(Tier.MEDIUM)
        conditions.update(
            {
                "hardBlockRateLegit": (action_high & legit, legit),
                "verificationRateLegit": (action_medium & legit, legit),
                "frictionTotalLegit": (action_friction & legit, legit),
                "hardBlockRateHardNegatives": (action_high & hard_negative, hard_negative),
                "verificationRateHardNegatives": (
                    action_medium & hard_negative,
                    hard_negative,
                ),
                "frictionTotalHardNegatives": (
                    action_friction & hard_negative,
                    hard_negative,
                ),
            }
        )
    return conditions


def _bootstrap_intervals(
    frame: pd.DataFrame,
    tiers: np.ndarray,
    rank_scores: np.ndarray,
    *,
    oob_resolvable: np.ndarray | None = None,
    seed: int = 0,
) -> dict[str, list[float]]:
    conditions = _metric_conditions(frame, tiers, oob_resolvable)
    draws: dict[str, list[float]] = {name: [] for name in conditions}
    draws["precisionAtAlertBudget"] = []
    n_rows = len(frame)
    budget = max(1, round(ALERT_BUDGET_FRACTION * n_rows))
    order = np.argsort(-rank_scores, kind="stable")
    labels = frame["label"].to_numpy(dtype=bool)
    rng = np.random.default_rng(seed)

    for _ in range(BOOTSTRAP_RESAMPLES):
        sample = rng.integers(0, n_rows, size=n_rows)
        for name, (numerator, denominator) in conditions.items():
            denominator_count = int(denominator[sample].sum())
            if denominator_count:
                draws[name].append(float(numerator[sample].sum() / denominator_count))
        weights = np.bincount(sample, minlength=n_rows)
        ordered_weights = weights[order]
        cumulative = np.cumsum(ordered_weights)
        cutoff = int(np.searchsorted(cumulative, budget, side="left"))
        before = int(cumulative[cutoff - 1]) if cutoff else 0
        positive_before = int(np.dot(ordered_weights[:cutoff], labels[order[:cutoff]]))
        remaining = budget - before
        positive_total = positive_before + min(remaining, int(ordered_weights[cutoff])) * int(labels[order[cutoff]])
        draws["precisionAtAlertBudget"].append(float(positive_total / budget))

    return {
        name: (
            [
                float(np.percentile(values, 2.5)),
                float(np.percentile(values, 97.5)),
            ]
            if values
            else [0.0, 0.0]
        )
        for name, values in draws.items()
    }


def _evaluate_predictions(
    frame: pd.DataFrame,
    scores: np.ndarray,
    tiers: np.ndarray,
    *,
    oob_resolvable: np.ndarray | None = None,
    p95_latency_ms: float | None = None,
    include_ci: bool = True,
    model_scores: np.ndarray | None = None,
) -> dict[str, Any]:
    # AUC and the alert-budget ranking rate the model's own score, not the rules-floored one.
    scores = scores if model_scores is None else model_scores
    labels = frame["label"].to_numpy(dtype=bool)
    amounts = frame["amount_eur"].to_numpy(dtype=float)
    typology = frame["typology"].astype(str).to_numpy()
    evasive = frame["evasive"].to_numpy(dtype=bool)
    hard_negative = frame["hard_negative"].to_numpy(dtype=bool) & ~labels
    flagged = tiers >= int(Tier.MEDIUM)
    high = tiers >= int(Tier.HIGH)
    legitimate = ~labels
    budget = max(1, round(ALERT_BUDGET_FRACTION * len(frame)))
    rank_scores = tiers.astype(np.int32) * 100 + scores.astype(np.int32)
    top = np.argsort(-rank_scores, kind="stable")[:budget]
    metrics: dict[str, Any] = {
        "recallT1": float(flagged[typology == "T1"].mean()),
        "recallT1Evasive": float(flagged[(typology == "T1") & evasive].mean()),
        "recallAll": float(flagged[labels].mean()),
        "precisionHigh": float(labels[high].mean()) if high.any() else 0.0,
        "fprMediumPlus": float(flagged[legitimate].mean()),
        "fprHardNegatives": float(flagged[hard_negative].mean()) if hard_negative.any() else 0.0,
        "stpRate": float((tiers[legitimate] == int(Tier.LOW)).mean()),
        "valueStoppedPct": float(amounts[flagged & labels].sum() / amounts[labels].sum()),
        "diversionRate": float(amounts[~flagged & labels].sum() / amounts.sum()),
        "precisionAtAlertBudget": float(labels[top].mean()),
        "alertBudget": int(budget),
        "auc": float(roc_auc_score(labels.astype(int), scores)),
    }
    if oob_resolvable is not None:
        action_tiers = _action_tiers(tiers, oob_resolvable)
        action_high = action_tiers >= int(Tier.HIGH)
        action_medium = action_tiers == int(Tier.MEDIUM)
        action_friction = action_tiers >= int(Tier.MEDIUM)
        metrics.update(
            {
                "hardBlockRateLegit": (
                    float((action_high & legitimate).sum() / legitimate.sum())
                    if legitimate.any()
                    else 0.0
                ),
                "verificationRateLegit": (
                    float((action_medium & legitimate).sum() / legitimate.sum())
                    if legitimate.any()
                    else 0.0
                ),
                "frictionTotalLegit": (
                    float((action_friction & legitimate).sum() / legitimate.sum())
                    if legitimate.any()
                    else 0.0
                ),
                "hardBlockRateHardNegatives": (
                    float((action_high & hard_negative).sum() / hard_negative.sum())
                    if hard_negative.any()
                    else 0.0
                ),
                "verificationRateHardNegatives": (
                    float((action_medium & hard_negative).sum() / hard_negative.sum())
                    if hard_negative.any()
                    else 0.0
                ),
                "frictionTotalHardNegatives": (
                    float((action_friction & hard_negative).sum() / hard_negative.sum())
                    if hard_negative.any()
                    else 0.0
                ),
            }
        )
    if p95_latency_ms is not None:
        metrics["ttdP95Ms"] = float(p95_latency_ms)
    if include_ci:
        metrics["confidenceIntervals95"] = _bootstrap_intervals(
            frame,
            tiers,
            rank_scores,
            oob_resolvable=oob_resolvable,
        )
    return metrics


def _typology_breakdown(frame: pd.DataFrame, tiers: np.ndarray, intervals: dict[str, list[float]]) -> list[dict[str, Any]]:
    typology = frame["typology"].astype(str).to_numpy()
    flagged = tiers >= int(Tier.MEDIUM)
    result = []
    for code in ("T1", "T2", "T3", "T4"):
        mask = typology == code
        result.append(
            {
                "typology": code,
                "count": int(mask.sum()),
                "recall": float(flagged[mask].mean()) if mask.any() else 0.0,
                "confidenceInterval95": intervals.get(f"recall{code}", [0.0, 0.0]),
            }
        )
    return result


def _legitimate_hold_breakdown(
    frame: pd.DataFrame, tiers: np.ndarray, rule_ids: np.ndarray
) -> dict[str, Any]:
    legitimate = ~frame["label"].to_numpy(dtype=bool)
    held = legitimate & (tiers >= int(Tier.MEDIUM))
    has_guarantee_rule = np.fromiter(
        (bool({"R-PV-01", "R-FL-01"}.intersection(ids)) for ids in rule_ids),
        dtype=bool,
        count=len(frame),
    )
    has_any_rule = np.fromiter(
        (bool(ids) for ids in rule_ids), dtype=bool, count=len(frame)
    )
    categories = {
        "guarantee": held & has_guarantee_rule,
        "otherRules": held & ~has_guarantee_rule & has_any_rule,
        "modelOnly": held & ~has_any_rule,
    }
    hold_count = int(held.sum())
    legitimate_count = int(legitimate.sum())
    return {
        "legitimateCount": legitimate_count,
        "heldCount": hold_count,
        "byCause": {
            name: {
                "count": int(mask.sum()),
                "shareOfHolds": float(mask.sum() / hold_count) if hold_count else 0.0,
                "shareOfLegitimate": (
                    float(mask.sum() / legitimate_count) if legitimate_count else 0.0
                ),
            }
            for name, mask in categories.items()
        },
    }


def _fit_lightgbm(
    train: pd.DataFrame,
    feature_names: list[str],
) -> lgb.LGBMClassifier:
    constraints = [
        int(next(monotone for name, _, monotone in FEATURES if name == feature))
        for feature in feature_names
    ]
    model = lgb.LGBMClassifier(
        objective="binary",
        n_estimators=240,
        learning_rate=0.05,
        num_leaves=15,
        max_depth=-1,
        min_child_samples=35,
        reg_lambda=1.0,
        random_state=20261001,
        n_jobs=1,
        deterministic=True,
        force_col_wise=True,
        monotone_constraints=constraints,
        verbosity=-1,
    )
    model.fit(
        _feature_frame(train).loc[:, feature_names],
        train["label"].to_numpy(dtype=int),
        feature_name=feature_names,
    )
    return model


def _baseline_models(
    seed_a: pd.DataFrame,
    seed_b: pd.DataFrame,
    rules_tiers: np.ndarray,
) -> list[dict[str, Any]]:
    train = seed_a.loc[seed_a["day"] <= 20]
    validation = seed_a.loc[seed_a["day"].between(21, 25)]
    labels_a = validation["label"].to_numpy(dtype=int)
    features_train = _feature_frame(train)
    features_validation = _feature_frame(validation)
    features_b = _feature_frame(seed_b)
    results: list[dict[str, Any]] = []

    logistic = make_pipeline(
        SimpleImputer(strategy="median", add_indicator=True),
        StandardScaler(),
        LogisticRegression(class_weight="balanced", random_state=0, max_iter=1_000, solver="liblinear"),
    )
    logistic.fit(features_train.loc[:, FEATURE_NAMES], train["label"].to_numpy(dtype=int))
    logistic_val = logistic.predict_proba(features_validation.loc[:, FEATURE_NAMES])[:, 1]
    med, high, *_ = _thresholds(logistic_val, labels_a)
    logistic_b = logistic.predict_proba(features_b.loc[:, FEATURE_NAMES])[:, 1]
    scores, tiers = _final_tiers(logistic_b, rules_tiers, med, high)
    results.append({"name": "logistic_regression", **_evaluate_predictions(seed_b, scores, tiers, include_ci=False)})

    no_bg = [name for name, family, _ in FEATURES if family not in {"B", "G"}]
    isolated = _fit_lightgbm(train, no_bg)
    isolated_val = isolated.predict_proba(features_validation.loc[:, no_bg])[:, 1]
    med, high, *_ = _thresholds(isolated_val, labels_a)
    isolated_b = isolated.predict_proba(features_b.loc[:, no_bg])[:, 1]
    scores, tiers = _final_tiers(isolated_b, rules_tiers, med, high)
    results.append({"name": "lightgbm_without_B_G", **_evaluate_predictions(seed_b, scores, tiers, include_ci=False)})

    rule_scores = np.zeros(len(seed_b), dtype=np.int16)
    rule_scores[rules_tiers >= int(Tier.CRITICAL)] = 95
    rule_scores[rules_tiers == int(Tier.HIGH)] = 75
    rule_scores[rules_tiers == int(Tier.MEDIUM)] = 55
    results.append({"name": "rules_only", **_evaluate_predictions(seed_b, rule_scores, rules_tiers, include_ci=False)})
    return results


def _ablations(seed_a: pd.DataFrame, seed_b: pd.DataFrame, rules_tiers: np.ndarray) -> list[dict[str, Any]]:
    train = seed_a.loc[seed_a["day"] <= 20]
    validation = seed_a.loc[seed_a["day"].between(21, 25)]
    labels_a = validation["label"].to_numpy(dtype=int)
    features_validation = _feature_frame(validation)
    features_b = _feature_frame(seed_b)
    results = []

    for family in ("B", "V", "P", "G", "H", "S", "R"):
        selected = [name for name, feature_family, _ in FEATURES if feature_family != family]
        model = _fit_lightgbm(train, selected)
        val_probabilities = model.predict_proba(features_validation.loc[:, selected])[:, 1]
        t_med, t_high, *_ = _thresholds(val_probabilities, labels_a)
        probabilities = model.predict_proba(features_b.loc[:, selected])[:, 1]
        scores, tiers = _final_tiers(probabilities, rules_tiers, t_med, t_high)
        metrics = _evaluate_predictions(seed_b, scores, tiers, include_ci=False)
        results.append(
            {
                "step": f"drop_{family}",
                "recallAtFpr": metrics["recallAll"],
                "recallAll": metrics["recallAll"],
                "recallT1Evasive": metrics["recallT1Evasive"],
                "fprMediumPlus": metrics["fprMediumPlus"],
                "auc": metrics["auc"],
            }
        )
    return results


def _integrity_replay() -> list[dict[str, Any]]:
    records = [
        json.loads(line)
        for line in (DATA_DIR / "integrity_cases.jsonl").read_text(encoding="utf-8").splitlines()
    ]
    outcomes: dict[str, list[bool]] = {}
    signer = Signer(env={})
    for index, record in enumerate(records):
        case = record["case"]
        clock = time.time()
        chain = MockChain(
            router_signers=[signer.address("router_signer")],
            verifier_signers=[signer.address("verifier_signer")],
        )
        original = record.get("original")
        amount_eur = float(original) if case == "I3" else 85_000.0
        payment_identifier = (
            str(original) if case == "I2" else str(record["paymentId"])
        )
        payment_id = to_hex(keccak_text(payment_identifier))
        intent = PaymentIntent(
            payment_id=payment_id,
            corridor_id=to_hex(keccak_text("FR-GH")),
            beneficiary=dev_address("gh_vasp"),
            token="0x0000000000000000000000000000000000000e0c",
            amount=int(amount_eur * 10**6),
            offchain_hash=hash_record({"field": record["field"], "value": original}),
            decision_hash=hash_record({"decision": payment_identifier}),
            approval_hash=hash_record({"approval": payment_identifier}),
            tier=int(Tier.MEDIUM),
            valid_until=int(clock) + 600,
            nonce=index,
        )
        router_sig = signer.sign("router_signer", intent, chain.domain())
        try:
            chain.commit(intent, router_sig)
            if case == "I2":
                chain.commit(intent, router_sig)
            else:
                tampered = record["tampered"]
                tampered_intent = intent.model_copy(
                    update={
                        "amount": int(float(tampered) * 10**6) if case == "I3" else intent.amount,
                        "offchain_hash": hash_record({"field": record["field"], "value": tampered}),
                    }
                )
                attestation = VerificationAttestation(
                    payment_id=payment_id,
                    intent_hash=to_hex(digest(tampered_intent, chain.domain())),
                    method=1,
                    result=int(VerificationResult.CONFIRMED),
                    sim_swap_checked=True,
                    evidence_hash=hash_record({"case": case, "tampered": tampered}),
                    verified_at=int(clock),
                    nonce=index,
                )
                chain.record_verification(
                    attestation,
                    signer.sign("verifier_signer", attestation, chain.domain()),
                )
            refused = False
        except ChainReverted as error:
            expected_reason = "InvalidTransition" if case == "I2" else "CommitmentMismatch"
            if error.reason != expected_reason:
                raise
            refused = True
        outcomes.setdefault(case, []).append(refused)
    return [
        {
            "case": case,
            "count": len(values),
            "refusedPct": float(np.mean(values) * 100),
        }
        for case, values in sorted(outcomes.items())
    ]


